//! Common English-prose given names and the gender they conventionally carry.
//!
//! A fixed, compact list rather than a census: it backs heuristic person
//! extraction and coreference gender inference when neither a model nor the
//! text supplies evidence, so it favours precision over coverage. Names that
//! double as ordinary capitalised words (months, virtues), well-known places
//! (Washington, Paris) or that are commonly used for either gender are left
//! out or listed as unisex.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum GivenNameGender {
    Male,
    Female,
    Unisex,
}

/// The conventional gender of `word` when it is a listed given name. The
/// lookup ignores case and a trailing possessive is not stripped.
pub fn given_name_gender(word: &str) -> Option<GivenNameGender> {
    let lower = word.to_lowercase();
    let lower = lower.as_str();
    if MALE.binary_search(&lower).is_ok() {
        Some(GivenNameGender::Male)
    } else if FEMALE.binary_search(&lower).is_ok() {
        Some(GivenNameGender::Female)
    } else if UNISEX.binary_search(&lower).is_ok() {
        Some(GivenNameGender::Unisex)
    } else {
        None
    }
}

