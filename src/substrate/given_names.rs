#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_disjoint() {
        for table in [MALE, FEMALE, UNISEX] {
            assert!(
                table.windows(2).all(|pair| pair[0] < pair[1]),
                "unsorted table"
            );
        }
        for name in MALE {
            assert!(FEMALE.binary_search(name).is_err() && UNISEX.binary_search(name).is_err());
        }
        for name in FEMALE {
            assert!(UNISEX.binary_search(name).is_err());
        }
    }

    #[test]
    fn lookup_ignores_case_and_rejects_words() {
        assert_eq!(given_name_gender("Tom"), Some(GivenNameGender::Male));
        assert_eq!(given_name_gender("MARY"), Some(GivenNameGender::Female));
        assert_eq!(given_name_gender("Robin"), Some(GivenNameGender::Unisex));
        assert_eq!(given_name_gender("London"), None);
        assert_eq!(given_name_gender("May"), None);
    }
}
